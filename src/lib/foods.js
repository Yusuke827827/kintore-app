const COUNTERS = '個|枚|本|杯|切れ|切|玉|皿|丁|パック|缶|貫|食|膳'

function findFood(text) {
  let best = null
  for (const food of FOODS) {
    for (const key of [food.name, ...food.aliases]) {
      if (text.includes(key) && (!best || key.length > best.key.length)) best = { food, key }
    }
  }
  return best?.food ?? null
}

// 1品分の栄養（g指定・個数指定・大盛り/少なめに対応）
function amountOf(food, text) {
  const grams = text.match(/(\d+(?:\.\d+)?)\s*(g|グラム)/i)
  let factor
  if (grams) {
    const g = Number(grams[1])
    factor = food.unit === 'g' ? g / 100 : g / food.size
  } else {
    const count = text.match(new RegExp(`(\\d+(?:\\.\\d+)?)\\s*(${COUNTERS})`)) ?? text.match(/(\d+(?:\.\d+)?)/)
    const n = count ? Number(count[1]) : 1
    factor = food.unit === 'g' ? (n > 10 ? n / 100 : (food.size / 100) * n) : n
  }
  if (/大盛|特盛/.test(text)) factor *= 1.5
  if (/少なめ|小盛|半分|ハーフ/.test(text)) factor *= 0.6
  return factor
}

// 「鶏むね肉200g、ご飯大盛り、卵2個」→ 品目ごとの栄養（見つからなかった言葉も返す）
export function parseMealText(text) {
  const tokens = text
    .split(/[、,，\n・＋+]|と(?=[^\d]{1,})|[\s　]+/)
    .map((s) => s.trim())
    .filter(Boolean)
  // 量や大きさだけの言葉（「大盛り」「2個」など）は前の食品にくっつける
  const modifier = new RegExp(`^(\\d+(\\.\\d+)?\\s*(g|グラム|${COUNTERS})?|大盛り?|特盛り?|少なめ|小盛り?|半分|ハーフ)$`)
  const parts = []
  for (const tok of tokens) {
    if (parts.length > 0 && !findFood(tok) && modifier.test(tok)) parts[parts.length - 1] += tok
    else parts.push(tok)
  }
  const items = []
  const unknown = []
  for (const part of parts) {
    const food = findFood(part)
    if (!food) {
      unknown.push(part)
      continue
    }
    const k = amountOf(food, part)
    const r = (v) => Math.round(v * k * 10) / 10
    items.push({ name: part, kcal: Math.round(food.kcal * k), p: r(food.p), f: r(food.f), c: r(food.c) })
  }
  return { items, unknown }
}

export function searchFoods(q) {
  const s = q.trim()
  if (!s) return FOODS.slice(0, 20)
  return FOODS.filter((f) => f.name.includes(s) || f.aliases.some((a) => a.includes(s)))
}

export function foodLabel(food) {
  return food.unit === 'g' ? `${food.name}（100g）` : `${food.name}（1${food.unit}）`
}
